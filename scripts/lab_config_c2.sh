#!/bin/bash
# C2完全独立3経路環境用パラメータ (LAB_MODE=c2)
#
# 構成: コンテナ群はPC(virttrx)上、コアリンク3本はそれぞれ専用の物理NICペアで
#   PC 10G NIC → SW1 ASIC → 専用クロスケーブル → SW2 ASIC → PC 10G NIC
#   (VLAN 201/202/203でアクセスポート化。C1と異なり1リンク1クラス専用、VLANタグ不要)
#
# C1からの変更点: 3経路が物理的に完全独立のため、他クラスとのワイヤ共有を
# 気にする必要がない。CR_BW=9GはC1と同じ理由(HTBが厳密にボトルネックである
# ことを保証する10%マージン)で踏襲。1クラスあたりの総送信量もC1と同じ8Gとし、
# veth/C1/C2で理論値を横並びに比較できるようにする
# (当初は 4本×2G。2026-09-17 以降は 64本×125000K、下記参照)。
#
# 2026-07-21 Phase検証: 9本の配線をflapテストで確認済み、3経路とも疎通(損失0%)。
# 生ファブリック(HTB整形なし)での3系統同時9.5Gテストでは経路2/3に大きな損失が
# 出たが、これはPC本体のCPU/PCIe限界であり、HTB整形後の実需要(最大8G級)なら
# 問題にならないと判断(project_c2_independent_paths.md参照)。
#
# 期待値 (単一の 9G リンク、HTB保証1/10縮小方式、全クラス需要8G):
#   AF41: 8G無損失 (保証0.9G + Yellow借用で需要8Gを満たす)
#   AF42: ≈0.667G (保証0.257G + 残りYellow 0.614G の 2/3)
#   AF43: ≈0.333G (保証0.129G + 残りYellow 0.614G の 1/3)
#   合計 9.0G。(2026-09-25 訂正: 以前は AF43≈0.44G と書いていたが計算誤り)

# ---------------------------------------------------------------------------
# 2026-09-17: ストリーム数を 4 → 128 に増やした。総送信量 8G/クラスは不変
#   (128 × 62500K = 8G)。オーバーサブスクリプションの設計も変わらない。
#
# 理由: 経路分配の粒度。Linux の重み付きマルチパス(WCMP)はフロー単位
#   (5-tuple ハッシュ)で振り分けるため、1本の通信を途中で分割できない。
#   12本(3クラス×4)では容量比 1:10:10 を表現できず、無線経路に割り当たるのが
#   期待値 0.57本 = 実際には 0本か1本。どちらになるかはハッシュ次第で、
#   実行のたびに結果が変わり再現性が無かった。
#   384本(3クラス×128)なら無線経路の割当は 18.3本 ± 23% に収まる。
#   実インターネットに近づけるという観点でも、12本は極端に少ない。
#
# iperf3 の -P 上限は 1インスタンスあたり 128 だが、128 では接続の取りこぼしが起きた。
#   2026-09-17 実測: AF42 が 128本中 126本しか確立できず iperf3 全体が abort し、
#   failure_reroute で AF42 が丸ごと欠測 (3シナリオ中1回発生)。
#   iperf3 は UDP モードでも制御用に TCP 接続を張るため、128本を一斉に張ると
#   サーバ側の accept キューが溢れる。iperf3 の listen() バックログは小さい固定値で
#   渡されるため somaxconn を上げても効かない。1本でも失敗すると計測全体が中断する。
#   → 64 に下げて同時接続数を半減させた。192本(3クラス分)でも 12本比で16倍であり、
#     量子化問題の解消という目的は達成できる (無線経路の割当 9.1本 ± 32%)。
# ---------------------------------------------------------------------------
IPERF_STREAMS="${IPERF_STREAMS:-64}"
TX1_RATE="${TX1_RATE:-125000K}"  # AF41: 64×125000K=8G。有線(9G)では無損失、無線では律速
TX2_RATE="${TX2_RATE:-125000K}"  # AF42: 64×125000K=8G >> 2/7×9G=2.57G → 意図的輻輳
TX3_RATE="${TX3_RATE:-125000K}"  # AF43: 64×125000K=8G >> 1/7×9G=1.29G → 意図的輻輳

# ---------------------------------------------------------------------------
# 2026-09-08: 経路1を 60GHz 無線2ホップに置換 (RADWIN TerraNet V90 x4)
#
# CR1 のみ無線、CR2/CR3 は有線のまま。有線無線ハイブリッド構成となる。
#
# 実測値 (ODU内蔵 SpeedTest / docs/radwin_integration_plan.md 参照):
#   無線1 (ch1, 3m, -38dBm, MCS12): TX 2610 / RX 2404 Mbps
#   無線2 (ch4, 2m, -26dBm, MCS12): TX 2438 / RX 2391 Mbps
#   4台とも ETH0 は 2.5Gbps full duplex
#   (2026-09-24 訂正: 当初「銅は瓶首でなく無線が容量を決めている」と書いたが逆。
#    無線そのものは MCS12 で約 2624 Mbps 運べ、瓶首は ODU の 2.5GbE ポート
#    (実効 約 2475 Mbps)。経路の実測 約 2.4 Gbps はこのポートで頭打ちした値)
#
# 実験のトラフィックは LER_Ingress→LER_Egress の一方向なので、その向きの
# ボトルネックは無線2の TX 2438 Mbps。安全側に実測最小の 2391 Mbps を採り、
# 既存の設計則 (物理の90% = 10%マージン) を踏襲して 2391 × 0.9 ≈ 2.1G とする。
#
# 【重要な帰結】AF41 の需要 8G がリンク容量 2.1G を大きく超えるため、
# 従来の「AF41 は無損失」は成立しない (約74%損失)。ただし SP の実証自体は成立し、
# AF41 がリンクをほぼ占有 (約2.0Gbps)・AF42/AF43 はほぼゼロ、という形で
# より際立って観測されるはず。failure シナリオで有線 CR2 (9G) へ迂回すると
# AF41 が 8G 無損失に回復するため、有線/無線の容量差が QoS に与える影響を
# 同一計測内で対比できる。
# ---------------------------------------------------------------------------
# 注: "2.1G" のような小数表記は使わないこと。scripts 内の rate_to_kbps() は
# 非数字を除去する実装のものが複数あり、"2.1G" が 21G と誤解釈されて
# HTB の保証帯域が 10 倍になる (SP 設計が壊れる)。必ず整数の M 表記にする。
#
# 【基準値】2026-09-18: アンテナ再アライメント後の実測に基づく。この状態を基準とする。
#   c2_path1_probe.sh の UDP スイープ (アライメント後):
#     500M→0.000% / 1000M→0.004% / 1500M→0.056% / 2000M→0.214%
#     2200M→0.110% / 2400M→0.533%   ← 上限まで損失1%未満で頭打ちが出ない
#   c2_fabric_test.sh 単独測定: 2.383 Gbps / 損失 0.284%
#   ODU SpeedTest: 無線1 TX2610 / 無線2 TX2438 (鎖の瓶首は無線2の約2.4G)
#   → 実容量 約 2.4 Gbps。既存の設計則 (実容量の90%) より 2400×0.9 = 2160M。
#
#   参考: アンテナがずれていた時は実効 1.05 Gbps まで落ち CR1_BW=900M だった
#   (results/frr/radwin/comparison/20260918_ecmp_nopolice, 20260918_wcmp がその条件のデータ)。
#   60GHz はビーム幅が狭く、わずかなずれで容量が半減する。
CR1_BW="${CR1_BW:-2160M}"     # 無線経路の初期値。経路の実測 約2.4Gbps (ODU の 2.5GbE ポートで頭打ち) × 0.9
                              # 動的制御 (radwin_wcmp_controller.py) の実行中は MCS から推定した値で上書きされる
CR2_BW="${CR2_BW:-9G}"        # 有線 (10G物理の90%)
CR3_BW="${CR3_BW:-9G}"        # 有線 (10G物理の90%)

# iperf3 の UDP データグラム長。経路上の最小 MTU に収まる必要がある。
#   CR1(無線) の cr1-lere は MTU 7800、CR2/CR3(有線) は 9100。
#   トラフィックは障害時に CR1↔CR2 を行き来するので、最小の 7800 に合わせる。
#   7000 + 8(UDP) + 20(IP) + 4(MPLSラベル) = 7032 < 7800 で余裕を持たせている。
# 2026-09-11: 既定の 8950 のままだと 8950+32=8982 > 7800 で CR1 経由時に
#   送信できず、normal シナリオのスループットが 0 になっていた。
# ---------------------------------------------------------------------------
# 経路分配モード (2026-09-17 追加)
#   primary … CR1 を主経路、CR2/CR3 をフォールバックにする従来方式。
#             normal では CR1 しか使わないため、無線1本に24Gが集中する。
#   ecmp    … 3経路を等重みで使う。Linux 既定のマルチパスと同じ挙動で、
#             経路の容量を考慮しない。弱い無線経路が過負荷になる。
#             → 「容量を見ないと何が起きるか」を示すベースライン。
#   wcmp    … 3経路を容量比で重み付けする。提案手法。
#
# 重要: マルチパスはフロー単位(5-tupleハッシュ)で振り分けるため、
#   net.ipv4.fib_multipath_hash_policy=1 (L3+L4ハッシュ) が必須。
#   既定の 0 だと送信元/宛先IPだけで決まり、同一クラスの全フローが
#   同じ経路に行ってしまう。frr_dscp_te.sh で設定している。
#
# 重みは CR_BW の比を既定にする。
#   2160M : 9G : 9G = 2160 : 9000 : 9000 → 最大公約数360で割って 6 : 25 : 25
#   無線への割当は 6/56 = 10.7% → 192フロー中 20.6本 ± 21%
#   各経路の輻輳率は一律 24G ÷ 20.16G = 1.19倍
# CR_BW を変えたら必ずこの比も更新すること (不一致だと分配が容量に合わなくなる)。
# ---------------------------------------------------------------------------
ROUTE_MODE="${ROUTE_MODE:-primary}"

# 入口ポリサー (leri-tx1/2/3) の有効/無効。
#   auto … ROUTE_MODE=primary のときだけ有効 (既定)
#   on   … 常に有効   /   off … 常に無効
#
# 2026-09-18: マルチパス時はポリサーを切る。理由は下記。
#   ポリサーは 全経路の合計容量(18.9G)を 4:2:1 に配分した値
#   (AF41 10.8G / AF42 5.4G / AF43 2.7G) で各クラスを入口で絞る。
#   単一経路(CR1のみ)ではリンク容量 0.9G の方がはるかに厳しく、
#   ポリサーは何もしていなかったので影響がなかった。
#   しかしマルチパスでは合計容量がポリサー値と近くなり、
#   **クラス間の差をポリサーが作ってしまう**。
#   2026-09-18 実測: ECMP で AF41:AF42:AF43 = 6.90:3.73:1.86 となったが、
#   これはリンクのHTBではなくポリサーによる 4:2:1 だった
#   (CR2/CR3 の HTB ドロップはゼロ = 輻輳していない)。
#   経路分配が QoS に与える影響を測るには、ポリサーを外す必要がある。
INGRESS_POLICE="${INGRESS_POLICE:-auto}"
WCMP_W1="${WCMP_W1:-6}"    # CR1 (無線 2160M)
WCMP_W2="${WCMP_W2:-25}"   # CR2 (有線 9G)
WCMP_W3="${WCMP_W3:-25}"   # CR3 (有線 9G)

IPERF_DGRAM="${IPERF_DGRAM:-7000}"

CR1_DELAY="${CR1_DELAY:-0ms}"
CR2_DELAY="${CR2_DELAY:-0ms}"
CR3_DELAY="${CR3_DELAY:-0ms}"

WRR_HI="${WRR_HI:-4}"
WRR_ME="${WRR_ME:-2}"
WRR_LO="${WRR_LO:-1}"

PFIFO_LIMIT_HI="${PFIFO_LIMIT_HI:-1000}"
PFIFO_LIMIT_ME="${PFIFO_LIMIT_ME:-2000}"
PFIFO_LIMIT_LO="${PFIFO_LIMIT_LO:-4000}"

# C2完全独立3経路のNIC割り当て (frr_setup.sh の連想配列 C2_NIC_SW1/SW2 が参照する値と一致させること)
